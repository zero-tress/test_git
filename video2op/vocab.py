# ---------------------------------------------------------------
# 约束元（C_const）的分类：决定"这条约束要不要一条覆盖全程的保持动作"
#
#   保持类 hold    需要某个执行器在过程中持续维持该状态（保持抓握 / 保持托举 /
#                  保持位姿 / 维持支撑）。这类约束必须在图上有落点：要么该操作内部
#                  有覆盖全程的保持动作，要么它被提升为一条独立的 MAINTAIN 操作。
#  安全类 safety  由规划与控制器保证的边界条件（不碰撞 / 不滑落 / 不倾倒 /
#                  不损伤）。它不需要"一条保持动作"来承担，运行期靠规划与力控守住。
#  局部类 local   只在某个瞬间成立的质量要求（合拢时要稳定接触、释放时不许拖动），
#                  由该动作自身的执行质量保证，不是跨时段的持续状态。
#
# 把两者混在一起会让每个操作都被标成"缺少覆盖全程的保持动作"——安全约束永远
# 等不到一条保持动作，于是"可启动性"全部为假，判据也就失去了意义。
# ---------------------------------------------------------------
