def constraint_kind(text: object) -> str:
    """约束元分类：hold（需要保持动作覆盖）/ safety（规划与控制器保证）/ local（动作质量）。"""
    t = str(text or "")
    if not t:
        return CONSTRAINT_KIND_SAFETY
    if any(w in t for w in SAFETY_WORDS):
        return CONSTRAINT_KIND_SAFETY
    if any(w in t for w in HOLD_WORDS):
        return CONSTRAINT_KIND_HOLD
    return CONSTRAINT_KIND_SAFETY


def hold_category(text: object) -> str:
    """保持类约束 / 保持动作的细分类别：grasp / support / contact / pose。"""
    t = str(text or "")
    for cat, words in HOLD_CATEGORY_WORDS.items():
        if any(w in t for w in words):
            return cat
    return "pose"


# ---------------------------------------------------------------
# 保持动作的宾语：维持的是执行器自己的状态，还是物体在世界中的状态
#
# “保持”后面紧跟的词决定这条保持是不是执行器的操作：
#   · 自身姿态 / 自身动作状态 / 对物体的作用 → 执行器自己的操作，够格的可以提升为
#     MAINTAIN 调度单元（保持位置 / 保持伸出 / 保持抓握 / 保持接触）；
#   · 维持物体在世界中的位置（“右臂保持燕麦杯在桌面近处位置”）→ 执行器其实只是停在
#     原地等下一步（释放），这一步不以操作为目的，不提升为节点——它留在所属操作里当
#     内部步骤，判定见 operations._independent_hold。
# ---------------------------------------------------------------
SELF_HOLD_WORDS = (
    "位置", "位姿", "姿态", "姿势", "高度", "朝向",           # 自身姿态
    "伸出", "抬起", "托举", "支撑", "悬停", "静止", "不动", "停留",  # 自身动作状态
    "抓握", "握持", "夹持", "抓紧", "握紧", "接触", "贴合", "压住",  # 对物体的作用
    "稳定", "平稳", "平衡", "张开", "闭合", "合拢",
)
HOLD_VERB_WORDS = ("保持", "维持", "持续")
SELF_HOLD_SCAN = 2          # 词表全是双字词：“保持”后的首二字就是它有在保持什么


def _hold_tail(text: str) -> str:
    """取出“保持 / 维持 / 持续”之后的文本（没有这些词时返回原文）。"""
    for w in HOLD_VERB_WORDS:
        i = text.find(w)
        if i >= 0:
            return text[i + len(w):].strip()
    return text


def is_self_hold(text: object) -> bool:
    """这条保持维持的是执行器自己的状态 / 对物体的作用吗。

    “右臂保持位置”“右手保持抓握燕麦杯” → 真：宾语是执行器的姿态或它对物体的作用，
    执行器确实被这件事占着，可以成为独立的 MAINTAIN 节点。
    “右臂保持燕麦杯在桌面近处位置”“右臂保持杯子的位置” → 假：宾语是物体在世界中的
    位置，手臂只是停在原地等释放，不是一步操作（用户口径：这个节点不以操作为目的）。

    判定取“保持 / 维持 / 持续”之后的首二字：执行器能保持的东西都是双字词
    （位置 / 伸出 / 抓握 / 托举 …），宾语是物体名（燕麦杯 / 杯子）时首二字落不进词表。
    """
    tail = _hold_tail(str(text or ""))
    return any(w in tail[:SELF_HOLD_SCAN] for w in SELF_HOLD_WORDS)


def is_hold_constraint(text: object) -> bool:
    return constraint_kind(text) == CONSTRAINT_KIND_HOLD


