def part_functions_text(parts: list[str] | None = None) -> str:
    """把部位功能先验拼成 prompt 可读文本（不含不参与操作的部位）。"""
    parts = parts or BODY_PARTS
    lines = []
    for p in parts:
        if p in IGNORED_PARTS:
            continue
        if p in PART_FUNCTIONS:
            lines.append(f"- {p}：{'、'.join(PART_FUNCTIONS[p])}（不给力时：{REST_STATE.get(p, '未知')}）")
    return "\n".join(lines)
